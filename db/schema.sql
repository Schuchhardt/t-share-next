create or replace function tshare_bump_saved_count()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    update tshare_activities set saved_count = saved_count + 1 where id = new.activity_id;
  elsif tg_op = 'DELETE' then
    update tshare_activities set saved_count = greatest(saved_count - 1, 0) where id = old.activity_id;
  end if;
  return null;
end;
$$;

create or replace function tshare_bump_download_count()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    update tshare_activities set download_count = download_count + new.quantity
      where id = new.activity_id;
  elsif tg_op = 'UPDATE' then
    update tshare_activities set download_count = greatest(download_count + new.quantity - old.quantity, 0)
      where id = new.activity_id;
  elsif tg_op = 'DELETE' then
    update tshare_activities set download_count = greatest(download_count - old.quantity, 0)
      where id = old.activity_id;
  end if;
  return null;
end;
$$;

drop trigger if exists tshare_saved_activities_count on tshare_saved_activities;
create trigger tshare_saved_activities_count
  after insert or delete on tshare_saved_activities
  for each row execute function tshare_bump_saved_count();

drop trigger if exists tshare_activity_downloads_count on tshare_activity_downloads;
create trigger tshare_activity_downloads_count
  after insert or update or delete on tshare_activity_downloads
  for each row execute function tshare_bump_download_count();

-- Recomputes both counters from the source tables. The import upserts rows,
-- which would otherwise let the triggers double-count on a re-run.
create or replace function tshare_refresh_activity_counters()
returns void
language sql
security definer
set search_path = public
as $$
  update tshare_activities a
  set saved_count =
        (select count(*)::int from tshare_saved_activities s where s.activity_id = a.id),
      download_count =
        (select coalesce(sum(d.quantity), 0)::int from tshare_activity_downloads d
         where d.activity_id = a.id);
$$;

comment on function tshare_refresh_activity_counters() is
  'Recomputes tshare_activities.saved_count / download_count from their source tables.';

