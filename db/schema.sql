-- =============================================================================
--  T-share · Supabase schema
-- =============================================================================
--  Replaces the MySQL database behind the Laravel API (t-share-back) and the
--  Angular front (t-share-front).
--
--  Conventions
--    * Every table is prefixed `tshare_` — the Supabase project is shared with
--      other apps, so the prefix is what keeps the namespace clean.
--    * Column names are English and normalised; `db/legacy-map.ts` records the
--      Spanish column each one came from.
--    * Access is service-role only (no Supabase Auth, no RLS). The Next.js
--      server is the single writer; nothing here is reachable from a browser.
--    * Legacy integer ids are preserved so every foreign key in the CSV export
--      still resolves. Identity sequences are re-seeded at the end of the load.
--
--  Files live in S3 (the bucket is NOT migrated). Two columns carry them:
--    * `*_key`  — S3 object key, as written by the old Laravel app. Private
--                 objects; the app signs a temporary URL on read.
--    * `*_url`  — absolute URL, written by new uploads.
--  A row has one or the other; `src/lib/storage.ts` resolves both to a URL.
-- =============================================================================

