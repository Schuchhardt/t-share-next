-- The import writes legacy ids explicitly, which leaves every identity sequence
-- sitting at 1. This pushes each one past the highest id it now holds, so the
-- first row the app inserts does not collide. `db/scripts/migrate.ts` calls it
-- through PostgREST once the load finishes.
create or replace function tshare_reset_sequences()
returns table (table_name text, next_value bigint)
language plpgsql
security definer
set search_path = public
as $$
declare
  rec record;
  seq text;
  maxid bigint;
begin
  for rec in
    select c.relname::text as tbl
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'r' and c.relname like 'tshare\_%'
    order by c.relname
  loop
    seq := pg_get_serial_sequence('public.' || quote_ident(rec.tbl), 'id');
    continue when seq is null;
    execute format('select coalesce(max(id), 0) from public.%I', rec.tbl) into maxid;
    perform setval(seq, greatest(maxid, 1), maxid > 0);
    table_name := rec.tbl;
    next_value := maxid + 1;
    return next;
  end loop;
end;
$$;

comment on function tshare_reset_sequences() is
  'Re-seeds every tshare_* identity sequence past the largest id in its table. Run after a data import.';

commit;
